package week2;

public class contohOperatorFira {
    public static void main(String[] args) {
        int a = 60;
        int b = 20;
        int c = 10;

        System.out.println("Aritmatika Operator");
        System.out.println("Bilangan a = " + a);
        System.out.println("Bilangan b = " + b);
        System.out.println("Bilangan c = " + c);
        System.out.println("Hasil dari a + b + c = " + (a + b + c));
        System.out.println("Hasil dari a - b - c = " + (a - b - c));
        System.out.println("Hasil dari a * b = " + (a * b));
        System.out.println("Hasil dari a / b = " + (a / b));
        System.out.println("Hasil dari a % b = " + (a % b));
        System.out.println("Hasil dari a + b * c = " + (a + b * c));
        System.out.println("Hasil dari (a + b) * c = " + ((a + b) * c));

    }
}
